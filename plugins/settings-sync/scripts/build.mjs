import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { build } from "esbuild";

const root = fileURLToPath(new URL("..", import.meta.url));
const result = await build({
  absWorkingDir: root,
  entryPoints: ["server/contribute.ts"],
  outfile: "server/runtime.js",
  bundle: true,
  platform: "node",
  format: "esm",
  target: "node20",
  external: ["@getpaseo/plugin", "@getpaseo/plugin/*", "zod"],
  treeShaking: true,
  write: false,
  metafile: true,
  banner: { js: "// Generated by pnpm build; includes bundled and compiled @getpaseo/protocol 0.12.0.\n// Copyright (c) 2025-present Mohamed Boudra. Apache-2.0; full license in README.md." },
});
for (const output of Object.values(result.metafile.outputs)) {
  for (const entry of output.imports) {
    if (entry.external && !entry.path.startsWith("node:") && entry.path !== "zod" && !/^@getpaseo\/plugin(?:\/|$)/.test(entry.path)) {
      throw new Error(`Unbundled runtime dependency: ${entry.path}`);
    }
  }
}
const output = result.outputFiles[0].text.replace(/^\/\/ .*?node_modules\/(?:\.pnpm\/[^/]+\/node_modules\/)?(@getpaseo\/protocol\/.*)$/gm, "// bundled $1");
const destination = path.join(root, "server/runtime.js");
if (process.argv.includes("--check")) {
  const committed = await readFile(destination, "utf8");
  if (committed.replaceAll("\r\n", "\n") !== output) throw new Error("server/runtime.js is stale. Run pnpm build.");
} else {
  await writeFile(destination, output);
}
console.log(`Server distribution ${process.argv.includes("--check") ? "verified" : "built"}: ${Buffer.byteLength(output)} bytes`);
