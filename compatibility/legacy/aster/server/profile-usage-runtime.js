async function discover(scope, lookup = {}, fetchApi = fetch) {
  if (scope.kind === "session")
    lookup = {
      ...lookup,
      env: scope.env,
      home: scope.env.HOME || scope.env.USERPROFILE || homedir3()
    };
  const candidates = scope.kind === "global" ? await globalRoutes(lookup) : await sessionRoutes(scope, lookup);
  const accounts = [];
  for (const input of candidates) {
    const credentials = await resolveClaudeCredentials(input, lookup);
    if (!credentials) continue;
    const harness = {
      pi: "Pi",
      omp: "OMP",
      claude: "Claude",
      keychain: "Claude",
      "windows-credman": "Claude"
    }[input.route.store];
    const fallback = { key: hashAccountKey(JSON.stringify(input.route)), harness, input };
    if (credentials.expires !== void 0 && credentials.expires <= (lookup.now ?? Date.now)()) {
      accounts.push(fallback);
      continue;
    }
    try {
      const profile = await readProfile(
        credentials.oauth.accessToken,
        fetchApi,
        lookup.now ?? Date.now
      );
      accounts.push("status" in profile ? fallback : { ...profile, harness, input });
    } catch {
      accounts.push(fallback);
    }
  }
  return accounts;
}
