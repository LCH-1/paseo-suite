async function configuredClaudeProviders(lookup = {}) {
  const env = lookup.env ?? process.env;
  const home = lookup.home ?? homedir2();
  const directory = env.PASEO_HOME || join2(home, ".paseo");
  let raw;
  try {
    raw = await readFile2(join2(directory, "config.json"), "utf8");
  } catch (error) {
    if (error.code === "ENOENT") return [];
    throw error;
  }
  const config = JSON.parse(raw);
  const providers = config.agents?.providers ?? {};
  const result = [];
  for (const [id, provider] of Object.entries(providers)) {
    if (provider.enabled === false) continue;
    const seen = /* @__PURE__ */ new Set();
    const chain = [];
    let current = id;
    while (current && !seen.has(current)) {
      seen.add(current);
      const entry = providers[current];
      if (entry) chain.push(entry);
      if (current === "claude") {
        result.push({
          id,
          env: Object.assign({}, ...chain.reverse().map((item) => item.env ?? {}))
        });
        break;
      }
      current = entry?.extends;
    }
  }
  return result;
}

